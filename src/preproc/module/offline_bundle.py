"""Offline module bundle: emit a self-contained ``.sql`` for an air-gapped DB.

``preproc module bundle`` is the air-gap path. It writes ONE runnable ``.sql``
file that an operator hand-carries into a database with no internet egress and
runs in EXAplus/DbVisualiser. The file contains, for each selected module:

* the module's ``CREATE OR REPLACE LUA SCRIPT`` artifact (library-deployed only;
  a self-deployed module's script is installed by its own project), and
* its rule registration and provenance write as
  ``EXECUTE SCRIPT PREPROC.RULE_ENSURE`` / ``PREPROC.MODULE_REGISTER`` lines,

followed by a single ``EXECUTE SCRIPT PREPROC.REFRESH`` for the whole file.

This generator makes NO database connection and fetches artifacts from the
registry the same way the online path does (local checkout off disk, or an
injected reader). It reuses ``bundle.py``'s delimiter helpers so a Lua body's
semicolons are wrapped in a ``--/`` … ``/`` block and are never treated as
statement terminators, exactly like the engine's ``release.sql``.
"""

from __future__ import annotations

from pathlib import Path

from preproc.bundle import _emit_sql
from preproc.module.deploy import ArtifactStatement, fetch_and_verify_artifact, resolve_scope
from preproc.module.manifest import ObjectSpec
from preproc.module.registry import RegistryEntry, encode_objects

_HEADER = """\
-- =============================================================================
-- preproc module bundle — offline module deploy
-- =============================================================================
-- GENERATED by `preproc module bundle`. Hand-carry into an air-gapped database
-- and run the whole file in EXAplus or DbVisualiser. Each statement of a
-- module's artifact whose body contains a semicolon is wrapped between a
-- `--/` line and a lone `/` line so its body's semicolons are not taken as
-- statement terminators; every other statement (including the rule/provenance
-- registrations and the closing REFRESH) is plain `;`-terminated SQL. Requires
-- the preprocessor framework (PREPROC.RULE_ENSURE / MODULE_REGISTER / REFRESH)
-- already installed.
-- =============================================================================

"""


def _needs_block_delimiters(statement: ArtifactStatement) -> bool:
    """A statement needs ``--/`` … ``/`` wrapping rather than a bare ``;`` terminator.

    True whenever the body actually contains a semicolon (the correctness
    requirement: a ``;``-terminator would split the statement mid-body), and
    also for every script-creating statement (``… SCRIPT``) regardless of
    whether THIS PARTICULAR body happens to contain one — a script body is
    free-form source code that may gain an internal ``;`` in the next edit, so
    it is always emitted in the same hand-runnable block form.
    """
    if ";" in statement.sql:
        return True
    return statement.creates is not None and statement.creates.type.endswith("SCRIPT")


def _emit_statement(statement: ArtifactStatement) -> str:
    """Format one artifact statement for the bundle, preserving its body verbatim.

    ``statement.sql`` is VERBATIM from the splitter (no terminator normalisation
    was ever applied to it). A statement that needs block delimiters is wrapped
    between a ``--/`` line and a lone ``/`` line with its body emitted
    UNMODIFIED — critically, never routed through ``bundle._strip_terminator``,
    which would strip a trailing ``;`` a block body's own syntax may require
    (e.g. ``CREATE FUNCTION … END name;``). Anything else is plain SQL and is
    emitted ``;``-terminated instead.
    """
    if _needs_block_delimiters(statement):
        return f"--/\n{statement.sql}\n/\n\n"
    return _emit_sql(statement.sql)


def _sql_literal(value: object) -> str:
    """Render a Python value as a SQL literal for a generated EXECUTE SCRIPT line."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def _rule_ensure_call(entry: RegistryEntry, scope: tuple[str, str]) -> str:
    """Build the idempotent RULE_ENSURE call (client_pattern NULL, norefresh TRUE)."""
    scope_type, scope_value = scope
    args = [scope_type, scope_value, entry.phase, entry.script_name, entry.function, None, True]
    return "EXECUTE SCRIPT PREPROC.RULE_ENSURE(" + ", ".join(_sql_literal(a) for a in args) + ")"


def _module_register_call(
    entry: RegistryEntry,
    *,
    source_url: str | None,
    library_version: str | None,
    objects: tuple[ObjectSpec, ...],
) -> str:
    """Build the provenance MODULE_REGISTER call for an entry.

    The argument list MUST match ``PREPROC.MODULE_REGISTER``'s declared
    parameters exactly (see the CREATE header in ``install.py`` / ``bundle.py``):
    this line runs AFTER every artifact statement has already committed, so a
    missing argument leaves the module installed but unregistered.

    ``source_url`` (the registry the bundle was built from) and
    ``library_version`` (the release the index declared) are recorded for audit.
    ``objects`` (the deployed inventory, in file order) is encoded via
    ``registry.encode_objects`` — never hand-rolled here, since that function
    owns the wire format ``module_reclaim.lua`` parses back — and renders as SQL
    ``NULL`` when empty (a self-deployed module carries no artifact through the
    registry, so it has nothing to inventory).

    The encoded inventory is newline-separated, so it renders as a single-quoted
    literal spanning lines. That keeps the statement hand-runnable: no line of
    the literal carries a ``;``, a ``--``, or a lone ``/`` (a manifest rejects
    those characters in a declared type or name), so the statement still ends at
    the first ``;`` a client sees — with or without cross-line quote tracking.
    """
    args = [
        entry.name,
        entry.version,
        entry.source["repo"],
        entry.source["ref"],
        entry.sha256,
        entry.script_name,
        entry.function,
        entry.phase,
        entry.deploy_mode,
        source_url,
        library_version,
        encode_objects(objects),
    ]
    rendered = ", ".join(_sql_literal(a) for a in args)
    return f"EXECUTE SCRIPT PREPROC.MODULE_REGISTER({rendered})"


def build_offline_bundle(
    entries: list[RegistryEntry],
    registry: str,
    *,
    scope: tuple[str, str] | None = None,
    reader=None,
    library_version: str | None = None,
) -> tuple[str, int]:
    """Return the bundle ``.sql`` text and the number of statements it contains.

    For each library-deployed entry the artifact is fetched and sha256-verified
    (a tampered artifact aborts the bundle), split into its statements, and each
    statement is emitted in file order — wrapped in a ``--/`` … ``/`` block when
    its body contains a semicolon, plain ``;``-terminated otherwise. Every entry
    then gets a ``;``-terminated RULE_ENSURE and MODULE_REGISTER. A single
    closing REFRESH resolves all the new rules.

    ``registry`` is recorded as each row's provenance ``source_url`` and
    ``library_version`` (the release the index declared) as its library release.
    Each MODULE_REGISTER also records the pre-flighted ``plan.objects``
    inventory, so a module installed from the bundle can later be reclaimed with
    the same ownership boundary as one installed online.
    """
    body = _HEADER
    count = 0
    for entry in entries:
        objects: tuple[ObjectSpec, ...] = ()
        if entry.deploy_mode == "library-deployed":
            plan = fetch_and_verify_artifact(entry, registry, reader=reader)
            for statement in plan.statements:
                body += _emit_statement(statement)
                count += 1
            objects = plan.objects
        entry_scope = resolve_scope(entry, scope)
        body += _emit_sql(_rule_ensure_call(entry, entry_scope))
        body += _emit_sql(
            _module_register_call(
                entry, source_url=registry, library_version=library_version, objects=objects
            )
        )
        count += 2

    body += _emit_sql("EXECUTE SCRIPT PREPROC.REFRESH")
    count += 1
    return body, count


def run_offline_bundle(
    entries: list[RegistryEntry],
    registry: str,
    output_path: Path,
    *,
    scope: tuple[str, str] | None = None,
    reader=None,
    library_version: str | None = None,
) -> int:
    """Write the offline bundle to ``output_path`` with LF endings; return the statement count.

    ``newline="\\n"`` is REQUIRED, not cosmetic. The default translates every
    ``\\n`` to ``os.linesep``, which on a Windows CLI machine would put CRLF
    INSIDE the newline-separated inventory literal — and ``module_reclaim.lua``
    splits the recorded inventory on ``[^\\n]+``, so every object name but the
    last would carry a trailing ``\\r`` and its DROP would name an object that
    does not exist. Forcing LF also makes the bundle byte-identical across the
    platforms it may be generated on.
    """
    body, count = build_offline_bundle(
        entries, registry, scope=scope, reader=reader, library_version=library_version
    )
    output_path.write_text(body, encoding="utf-8", newline="\n")
    return count
